/// A type only clashes with a function name when a kept function declares it.
#[test]
fn only_types_of_kept_functions_shadow_a_function() {
    // `z_set_mode` alone would declare `mode`, but its local `account-id` conflicts with the core
    // one `set_owner` uses, so it is left out and `mode` stays a function name.
    let iface = component(
        r#"
pub type Account_Id = struct { suffix: felt, prefix: felt }
pub type AccountId = struct { prefix: felt, suffix: felt }

pub enum Mode : u8 {
    A = 0,
    B = 1,
}

@account_procedure
pub proc mode() -> u32
    nop
end

@account_procedure
pub proc set_owner(id: Account_Id)
    drop drop
end

@account_procedure
pub proc z_set_mode(id: AccountId, m: Mode)
    drop drop drop
end
"#,
    );
    let generated = generate(&iface).unwrap();
    let skipped: Vec<(&str, &str)> =
        generated.skipped.iter().map(|s| (s.path.as_str(), s.reason.as_str())).collect();
    assert_eq!(
        skipped,
        [(
            "miden::test::my_component::z_set_mode",
            "conflicting definitions of type `account-id` in one interface"
        )]
    );
    assert_eq!(
        parse(&generated.wit, "my-component"),
        [
            ("mode".to_owned(), "miden::test::my_component::mode".to_owned()),
            ("set-owner".to_owned(), "miden::test::my_component::set_owner".to_owned()),
        ]
    );
}

/// Several results become one tuple in manifest order, and results beyond the stack budget are
/// left out.
#[test]
fn several_results_become_a_tuple() {
    let iface = component(
        r#"
pub type ConversionRate = struct { num: felt, den: felt }
pub type Asset = struct { id: word, value: word }

@account_procedure
pub proc get_conversion_rate() -> (i1, ConversionRate)
    nop
end

@account_procedure
pub proc assets() -> (Asset, Asset, felt)
    nop
end
"#,
    );
    let generated = generate(&iface).unwrap();
    let skipped: Vec<(&str, &str)> =
        generated.skipped.iter().map(|s| (s.path.as_str(), s.reason.as_str())).collect();
    assert_eq!(
        skipped,
        [(
            "miden::test::my_component::assets",
            "results occupy 17 stack elements, more than the 16 a call can return"
        )]
    );
    assert!(
        generated
            .wit
            .contains("    get-conversion-rate: func() -> tuple<bool, conversion-rate>;\n"),
        "{}",
        generated.wit
    );
    assert!(
        generated.wit.contains(
            "    record conversion-rate {\n        num: felt,\n        den: felt,\n    }\n"
        ),
        "{}",
        generated.wit
    );
    parse(&generated.wit, "my-component");
}

