/// A left-out export path with a line break stays on its one `/// Left out:` comment line, and a
/// bidirectional override in it does not reach the document.
#[test]
fn a_line_break_in_a_left_out_path_stays_in_its_comment() {
    let mut iface = component(
        r#"
@account_procedure
pub proc ping()
    nop
end

@account_procedure
pub proc pong()
    nop
end
"#,
    );
    let injected = format!("{MODULE}::\"pong\n    bad: func();\r\u{202e}\"");
    iface.procedures[1].path = miden_mast_package::PathBuf::relative(&injected).into();
    let generated = generate(&iface).unwrap();
    assert_eq!(generated.skipped.len(), 1, "{:?}", generated.skipped);
    assert!(generated.skipped[0].path.contains('\n'), "{:?}", generated.skipped);
    let comments: Vec<&str> =
        generated.wit.lines().filter(|line| line.starts_with("/// Left out:")).collect();
    assert_eq!(comments.len(), 1, "{}", generated.wit);
    assert!(comments[0].contains("bad: func();"), "{}", generated.wit);
    assert!(!generated.wit.contains(['\r', '\u{202e}']), "{}", generated.wit);
    assert_eq!(
        parse(&generated.wit, "my-component"),
        [("ping".to_owned(), "miden::test::my_component::ping".to_owned())]
    );
}

/// A package name and a left-out reason carrying a line break and a bidirectional override, which
/// wit-parser rejects anywhere in a document, keep the document parsing.
#[test]
fn forbidden_characters_in_the_package_name_and_a_reason_are_replaced() {
    let mut iface = component(
        r#"
@account_procedure
pub proc ping()
    nop
end

@account_procedure
pub proc take(x: felt)
    drop
end
"#,
    );
    iface.name = miden_mast_package::PackageId::from("miden-test-my\u{202e}component\n");
    let take = iface
        .procedures
        .iter_mut()
        .find(|procedure| procedure.name() == "take")
        .unwrap();
    take.signature.as_mut().unwrap().params[0] = Type::from(midenc_hir_type::StructType::named(
        std::sync::Arc::from("miden:base/core-types@1.0.0/th\u{202e}ing\nbad: func();"),
        [(std::sync::Arc::from("x"), Type::Felt)],
    ));
    let generated = generate(&iface).unwrap();
    assert_eq!(generated.skipped.len(), 1, "{:?}", generated.skipped);
    assert!(generated.skipped[0].reason.contains("\u{202e}ing\n"), "{:?}", generated.skipped);
    assert!(
        generated.wit.starts_with(
            "// Generated by midenc-package-wit from package `miden-test-my component ` "
        ),
        "{}",
        generated.wit
    );
    assert!(!generated.wit.contains('\u{202e}'), "{}", generated.wit);
    let comments: Vec<&str> =
        generated.wit.lines().filter(|line| line.starts_with("/// Left out:")).collect();
    assert_eq!(comments.len(), 1, "{}", generated.wit);
    assert!(comments[0].contains("th ing bad: func();"), "{}", generated.wit);
    assert_eq!(
        parse(&generated.wit, "my-component"),
        [("ping".to_owned(), "miden::test::my_component::ping".to_owned())]
    );
}

/// Procedures with no WIT name or a reserved `fpi-`/`dyncall-` name are left out with a reason.
