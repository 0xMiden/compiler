/// The module every fixture component's procedures live in.
const MODULE: &str = "miden::test::my_component";

/// The interface of an account-component package assembled from `source` in [`MODULE`].
fn component(source: &str) -> PackageInterface {
    let mut package = (*assemble_fixture("miden-test-my-component", MODULE, source)).clone();
    package.kind = TargetType::AccountComponent;
    PackageInterface::from_package(&package)
}

/// Parse `wit` next to the SDK's core types, check that every function carries an
/// `@external-id`, and return the `(name, external id)` of each function of `interface`.
fn parse(wit: &str, interface: &str) -> Vec<(String, String)> {
    let mut resolve = wit_parser::Resolve::new();
    resolve.push_str("miden.wit", MIDEN_WIT).expect("the core types parse");
    let package = resolve
        .push_str("generated.wit", wit)
        .unwrap_or_else(|err| panic!("generated WIT must parse: {err:?}\n{wit}"));
    let id = resolve.packages[package].interfaces[interface];
    resolve.interfaces[id]
        .functions
        .values()
        .map(|function| {
            let external_id = function
                .external_id
                .clone()
                .unwrap_or_else(|| panic!("`{}` has no external id", function.name));
            (function.name.clone(), external_id)
        })
        .collect()
}

#[test]
fn the_component_interface() {
    let iface = component(COMPONENT);
    let generated = generate(&iface, &Options::default()).unwrap();
    assert_eq!(generated.package_id, "miden:test-my-component@0.0.0");
    assert_eq!(generated.interface, "my-component");
    assert_eq!(generated.world, "my-component-world");

    let skipped: Vec<(&str, &str)> =
        generated.skipped.iter().map(|s| (s.path.as_str(), s.reason.as_str())).collect();
    assert_eq!(
        skipped,
        [
            (
                "miden::test::my_component::digest",
                "results flatten to 4 values; multi-value results of Miden Assembly components \
                 are not supported yet"
            ),
            ("miden::test::my_component::halves", "unsupported type `[felt; 2]`"),
            (
                "miden::test::my_component::owner",
                "results flatten to 2 values; multi-value results of Miden Assembly components \
                 are not supported yet"
            ),
            (
                "miden::test::my_component::pair",
                "results flatten to 2 values; multi-value results of Miden Assembly components \
                 are not supported yet"
            ),
            (
                "miden::test::my_component::sparse",
                "unsupported type `Sparse`: an enum with non-contiguous discriminants"
            ),
            (
                "miden::test::my_component::too_wide",
                "parameters flatten to 17 stack values, more than the 16 a direct call can pass"
            ),
            ("miden::test::my_component::untyped", "no typed signature"),
        ]
    );
    let digest = iface.digest.to_string();
    let expected = format!(
        r#"// Generated by midenc-package-wit from package `miden-test-my-component` 0.0.0.
// Dependency commitment: {digest}.
// Skipped: miden::test::my_component::digest: results flatten to 4 values; multi-value results of Miden Assembly components are not supported yet
// Skipped: miden::test::my_component::halves: unsupported type `[felt; 2]`
// Skipped: miden::test::my_component::owner: results flatten to 2 values; multi-value results of Miden Assembly components are not supported yet
// Skipped: miden::test::my_component::pair: results flatten to 2 values; multi-value results of Miden Assembly components are not supported yet
// Skipped: miden::test::my_component::sparse: unsupported type `Sparse`: an enum with non-contiguous discriminants
// Skipped: miden::test::my_component::too_wide: parameters flatten to 17 stack values, more than the 16 a direct call can pass
// Skipped: miden::test::my_component::untyped: no typed signature
package miden:test-my-component@0.0.0;

interface my-component {{
    use miden:base/core-types@1.0.0.{{asset, felt, note-type, word}};

    enum mode {{
        fast,
        slow-and-steady,
    }}

    record account-id {{
        suffix: felt,
        prefix: felt,
    }}

    record nested {{
        owner: account-id,
        amount: u64,
    }}

    @external-id("miden::test::my_component::auth_tx")
    auth-tx: func(arg0: word);

    @external-id("miden::test::my_component::create_note")
    create-note: func(arg0: u32, note-type: note-type, arg2: word) -> u16;

    @external-id("miden::test::my_component::receive_asset")
    receive-asset: func(asset: asset);

    @external-id("miden::test::my_component::set_mode")
    set-mode: func(mode: mode) -> bool;

    @external-id("miden::test::my_component::set_owner")
    set-owner: func(account-id: account-id, nested: nested);

    @external-id("miden::test::my_component::swap")
    swap: func(asset: asset, asset2: asset) -> felt;
}}

world my-component-world {{
    export my-component;
}}
"#
    );
    assert_eq!(generated.wit, expected);

    let functions = parse(&generated.wit, "my-component");
    assert_eq!(functions.len(), 6);
    assert!(functions.contains(&(
        "receive-asset".to_owned(),
        "miden::test::my_component::receive_asset".to_owned()
    )));
}

#[test]
fn an_account_id_in_core_order_uses_the_core_type() {
    let iface = component(
        r#"
pub type AccountId = struct { prefix: felt, suffix: felt }

@account_procedure
pub proc set_owner(id: AccountId)
    drop drop
end
"#,
    );
    let generated = generate(&iface, &Options::default()).unwrap();
    assert!(generated.skipped.is_empty());
    assert!(generated.wit.contains("// Skipped: none\n"));
    assert!(generated.wit.contains("use miden:base/core-types@1.0.0.{account-id};"));
    assert!(generated.wit.contains("set-owner: func(account-id: account-id);"));
    assert!(!generated.wit.contains("record"));
    parse(&generated.wit, "my-component");
}

#[test]
fn a_function_without_parameters() {
    let iface = component(
        r#"
@account_procedure
pub proc ping()
    nop
end
"#,
    );
    let generated = generate(&iface, &Options::default()).unwrap();
    assert!(!generated.wit.contains("use "), "no core item is used");
    assert!(generated.wit.contains("    ping: func();\n"));
    parse(&generated.wit, "my-component");
}

#[test]
fn only_account_components_have_an_interface() {
    let package = assemble_fixture("miden-test-my-component", MODULE, COMPONENT);
    let iface = PackageInterface::from_package(&package);
    assert!(matches!(
        generate(&iface, &Options::default()),
        Err(Error::NotAComponent(TargetType::Library))
    ));
}

#[test]
fn a_component_needs_role_procedures() {
    let iface = component(
        r#"
pub proc helper(x: felt) -> felt
    nop
end
"#,
    );
    assert!(matches!(generate(&iface, &Options::default()), Err(Error::NoRoleProcedures)));
}

#[test]
fn a_quoted_export_path_is_skipped() {
    let iface = component(
        r#"
@account_procedure
pub proc ping()
    nop
end

@account_procedure
pub proc "with-dash"()
    nop
end
"#,
    );
    let generated = generate(&iface, &Options::default()).unwrap();
    assert_eq!(generated.skipped.len(), 1, "{:?}", generated.skipped);
    assert!(generated.skipped[0].path.contains('"'), "{:?}", generated.skipped);
    assert!(
        generated.skipped[0].reason.contains("which `@external-id` cannot spell"),
        "{:?}",
        generated.skipped
    );
    parse(&generated.wit, "my-component");
}
