//! Integration tests for account storage schemas stored in Miden packages.

use miden_account_storage_schema::{AccountStorageSchema, StorageSlotKind};
use miden_mast_package::Package;
use midenc_expect_test::{Expect, expect};
use midenc_frontend_wasm_metadata::{
    package_account_storage_schema_section_id, trim_trailing_nuls,
};
use midenc_integration_test_support::{compile_project, workspace_root};

use super::note_schema_metadata::EXPECTED_CORE_TYPES;

/// Returns the unpadded account storage schema text from a package.
fn account_storage_schema(package: &Package) -> &str {
    let section_id = package_account_storage_schema_section_id();
    let bytes = package
        .sections
        .iter()
        .find(|section| section.id == section_id)
        .expect("package must contain an account storage schema")
        .data
        .as_ref();
    assert_eq!(bytes.len() % 16, 0, "schema payload must use 16-byte padding");
    str::from_utf8(trim_trailing_nuls(bytes)).expect("account storage schema must be UTF-8")
}

/// Checks a schema golden and reads the package's slots with the host reader.
///
/// Each expected slot is its leaf name and whether it is a map.
fn assert_account_storage_schema(
    package: &Package,
    expected_slots: &[(&str, bool)],
    expected: Expect,
) {
    let source = account_storage_schema(package);
    let core_types_start = source
        .find("package miden:base@1.0.0 {")
        .expect("schema must contain the SDK core-types package");
    let (schema, core_types) = source.split_at(core_types_start);
    expected.assert_eq(schema);
    assert_eq!(core_types, EXPECTED_CORE_TYPES);

    let schema =
        AccountStorageSchema::from_package(package).expect("account storage schema must resolve");
    let slots = schema
        .slots()
        .iter()
        .map(|slot| (slot.leaf(), matches!(slot.kind(), StorageSlotKind::Map { .. })))
        .collect::<Vec<_>>();
    assert_eq!(slots, expected_slots);
}

#[test]
fn component_packages_carry_resolvable_storage_schema_metadata() {
    let workspace = workspace_root();
    let storage_example = compile_project(&workspace.join("examples/storage-example"));
    assert_account_storage_schema(
        &storage_example,
        &[
            ("owner_public_key", false),
            ("asset_qty_map", true),
            ("limits", false),
            ("holdings", true),
        ],
        expect![[r#"
            // This file is auto-generated by the `#[component_storage]` macro.
            // Do not edit this file manually.

            package miden:storage-example-storage-schema;

            use miden:base/core-types@1.0.0;

            interface account-storage {
                use core-types.{asset-amount, word};

                /// Limits that apply to the account's holdings.
                record limits {
                    /// The largest quantity of one holding.
                    %max-qty: asset-amount,
                    /// Whether the holdings are frozen.
                    %paused: bool,
                }

                /// The account's holding of one asset.
                record holding {
                    /// The quantity held.
                    %qty: asset-amount,
                    /// Whether the holding is locked.
                    %locked: bool,
                }

                /// An example account demonstrating storage value and map usage.
                record storage {
                    /// Public key authorized to update the stored asset quantities.
                    %owner-public-key: word,
                    /// A map from asset id word to quantity held by the account.
                    %asset-qty-map: list<tuple<word, asset-amount>>,
                    /// Limits that apply to the account's holdings.
                    %limits: limits,
                    /// A map from asset id word to the account's holding of that asset.
                    %holdings: list<tuple<word, holding>>,
                }
            }

        "#]],
    );

    let counter = compile_project(&workspace.join("examples/counter-contract"));
    assert_account_storage_schema(
        &counter,
        &[("count_map", true)],
        expect![[r#"
        // This file is auto-generated by the `#[component_storage]` macro.
        // Do not edit this file manually.

        package miden:counter-contract-storage-schema;

        use miden:base/core-types@1.0.0;

        interface account-storage {
            use core-types.{felt, word};

            /// Storage layout for the counter example.
            record storage {
                /// Storage map holding the counter value.
                %count-map: list<tuple<word, felt>>,
            }
        }

    "#]],
    );
}
